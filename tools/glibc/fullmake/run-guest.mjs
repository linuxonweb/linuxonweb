import {spawn} from 'node:child_process';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url)),[,out]=process.argv.slice(2);
const child=spawn(process.execPath,[path.join(here,'../syscalls/run-guest.mjs'),...process.argv.slice(2)],{stdio:'inherit',env:process.env});
const status=await new Promise(resolve=>child.once('exit',resolve));
const base=JSON.parse(await fs.readFile(path.join(out,'syscalls-result.json')));
const lines=(await fs.readFile(path.join(out,'guest-console.txt'),'utf8')).split(/\r?\n/);
const runs=lines.filter(x=>x==='GNU_WARNING_SYSCALLS metadata=preserved stub=GNU sigaltstack=ENOSYS result=PASS').length;
const report={pass:status===0&&base.pass&&runs===6,runs,altstackSupported:false,linkerWarningEnforcement:false};
await fs.writeFile(path.join(out,'warnings-result.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report));if(!report.pass)process.exitCode=1;
