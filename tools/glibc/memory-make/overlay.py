#!/usr/bin/env python3
"""Select explicit native memory providers while retaining GNU sbrk itself."""
import hashlib,json,os,pathlib,re
T=pathlib.Path(os.environ['GLIBC_TASK']);R=pathlib.Path(__file__).resolve().parent
S=T/'source/glibc-2.44';A=S/'sysdeps/unix/sysv/linux/wasm32';P=pathlib.Path(os.environ['GLIBC_STAT_RUNTIME_PACKET'])
source=R.parent/'port/wasm-memory.c';manifest=json.loads((P/'manifest.json').read_text())['files']
data=source.read_bytes();assert manifest[str(source)]=={'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest()}
text=data.decode();start=text.index('void *__sbrk(intptr_t increment) {');end=text.index('static size_t round_page',start)
text=text[:start]+(R/'break-authority.inc').read_text()+text[end:]
text=text.replace('static uintptr_t heap_begin, cursor;','static uintptr_t heap_begin, cursor, break_cursor;')
text=text.replace('heap_begin=cursor=aligned;','heap_begin=cursor=break_cursor=aligned;')
for n in ['mmap','munmap','mremap','mprotect','madvise']:
 text=re.sub(r'\b__'+n+r'\b','__wasm_memory_'+n,text)
(A/'wasm-memory-authority.c').write_text(text)
for p in R.glob('*.c'):
 if p.name!='fixture.c':(A/p.name).write_bytes(p.read_bytes())
make=A/'Makefile';make.write_text(make.read_text()+'\nifeq ($(subdir),misc)\nsysdep_routines += wasm-memory-authority\nendif\n')
paths=[A/'wasm-memory-authority.c',make,*[A/p.name for p in R.glob('*.c') if p.name!='fixture.c']]
(T/'logs/memory-overlay.json').write_text(json.dumps({'acceptedSource':str(source),'acceptedHash':manifest[str(source)],'changes':['independent logical break cursor','GNU sbrk calls selected native brk','growth rejects intervening mappings','logical shrink retains physical Wasm pages','private authority names prevent duplicate public providers'],'files':{str(p):{'bytes':p.stat().st_size,'sha256':hashlib.sha256(p.read_bytes()).hexdigest()}for p in paths}},indent=2)+'\n')

# Metadata was generated by the cumulative preparation before these owned
# providers existed. Regenerate GNU source selection instead of editing its
# generated rules or routing these APIs through absent kernel memory calls.
selection=T/"objects/fullmake/sysd-syscalls"
if selection.exists():
 (T/"logs/sysd-syscalls-before-memory-overlay").write_bytes(selection.read_bytes())
 selection.unlink()
