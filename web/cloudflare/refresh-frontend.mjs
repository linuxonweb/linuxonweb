#!/usr/bin/env node
// Update the mobile-keyboard frontend without resnapshotting guest artifacts.
import { createHash } from 'node:crypto';
import { createReadStream } from 'node:fs';
import { readFile, rename, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import assets from './generated/asset-manifest.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const generated = join(here, 'generated');
const report = JSON.parse(await readFile(join(generated, 'build-report.json'), 'utf8'));
const upload = JSON.parse(await readFile(join(generated, 'upload-manifest.json'), 'utf8'));
const frozenArchives = {
  '/linux/initramfs-firefox.cpio.gz': 'e726ede312e1164a2081f4294374774e02ac4574126ea1602889f442c477ca25',
  '/linux/initramfs.cpio': 'beea582d106e6454397611b8efaba1b89417269129303a981bae69978e8e5bb1',
};
for (const [path, expected] of Object.entries(frozenArchives)) {
  const entry = assets[path];
  const hash = createHash('sha256'); let size = 0;
  for (const part of entry.parts) for await (const bytes of createReadStream(join(here, 'public', part.path))) { hash.update(bytes); size += bytes.length; }
  if (entry.sha256 !== expected || hash.digest('hex') !== expected || size !== entry.size) throw new Error(`Frozen archive mismatch: ${path}`);
}
for (const name of ['index.html', 'main.js', 'mobile-keyboard.mjs']) {
  const source = `web/linux/${name}`;
  const path = `/linux/${name}`;
  const bytes = await readFile(join(here, '..', 'linux', name));
  if (bytes.length > 1024 * 1024) throw new Error('Unexpected frontend asset size');
  const sha256 = createHash('sha256').update(bytes).digest('hex');
  await writeFile(join(here, 'public', path), bytes);
  assets[path] = { size: bytes.length, sha256, contentType: name.endsWith('.html') ? 'text/html; charset=utf-8' : 'text/javascript; charset=utf-8', parts: [{ path, size: bytes.length }] };
  upload[path] = { hash: createHash('md5').update(bytes).digest('hex'), size: bytes.length };
  const record = { source, path, size: bytes.length, sha256, parts: 1 };
  const index = report.sourceFiles.findIndex(file => file.path === path);
  if (index < 0) report.sourceFiles.push(record); else report.sourceFiles[index] = record;
}
report.sourceFiles.sort((a, b) => a.path.localeCompare(b.path));
report.sourceBytes = report.sourceFiles.reduce((sum, file) => sum + file.size, 0);
report.stagedFiles = Object.keys(upload).length;
report.stagedBytes = Object.values(upload).reduce((sum, file) => sum + file.size, 0);
report.routes = Object.keys(assets).length;
const files = {
  'asset-manifest.mjs': `// Generated by stage-assets.mjs / refresh-frontend.mjs. Do not edit.\nexport default ${JSON.stringify(Object.fromEntries(Object.entries(assets).sort(([a], [b]) => a.localeCompare(b))), null, 2)};\n`,
  'upload-manifest.json': `${JSON.stringify(upload, null, 2)}\n`,
  'build-report.json': `${JSON.stringify(report, null, 2)}\n`,
};
for (const [name, text] of Object.entries(files)) {
  await writeFile(join(generated, name + '.tmp'), text);
  await rename(join(generated, name + '.tmp'), join(generated, name));
}
console.log(JSON.stringify({ refreshed: ['index.html', 'main.js', 'mobile-keyboard.mjs'], routes: report.routes, stagedFiles: report.stagedFiles, stagedBytes: report.stagedBytes, preservedArchives: frozenArchives }, null, 2));
