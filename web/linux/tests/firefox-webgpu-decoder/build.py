#!/usr/bin/env python3
"""Build the Firefox 128 WebGPU wire decoder (W3) as a standalone Wasm module.

Assembles an offline Cargo workspace under OUTPUT/ws:
  decoder/           this crate (Cargo.toml, src/*.rs)
  decoder/src/wire_generated.rs
                     preamble + gfx/wgpu_bindings items copied verbatim from
                     the Firefox 128.14.0 tree (private wire enums/structs),
                     + include!("wire_dispatch.rs")
  adapters/js-sys, adapters/web-sys
                     Firefox's dummy-web Cargo.toml (feature lists) with the
                     adapter lib.rs from this directory (four inert stand-in
                     types that wgpu-types names on wasm32-unknown-unknown)
  Cargo.lock         Firefox's Cargo.lock (hash-pinned; cargo prunes it)
  Cargo.toml         Firefox's [patch] tables, except js-sys/web-sys -> adapters
  .cargo/config.toml Firefox's source replacement -> third_party/rust, offline

Builds wasm32-unknown-unknown with no network, validates the module, checks
it has no imports, checks every resolved package matches Firefox's lock, and
writes build.json, source-lock.json and firefox-webgpu-decoder.wasm.

Usage: build.py --output /mnt/p6/build/firefox-webgpu-w3-20260929/decoder-build-runN
"""
import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
TASK = Path("/mnt/p6/build/firefox-webgpu-w3-20260929")
FF = Path("/mnt/p6/project/linux/.tmp-firefox-build/nix-local-store/nix/var/nix/"
          "builds/nix-721784-2625232085/build/firefox-128.14.0")
FF_LOCK_SHA256 = "3a72a0456cfe9ab0c2239852383a18c4a90a119c5dc684c0b56d513414114d3f"
TOOLCHAIN = Path("/home/a/.rustup/toolchains/stable-x86_64-unknown-linux-gnu")
CARGO = Path("/home/a/.cargo/bin/cargo")
CRATE_FILES = ["Cargo.toml", "src/lib.rs", "src/guard.rs", "src/wire_dispatch.rs",
               "adapters/js-sys/lib.rs", "adapters/web-sys/lib.rs"]

# (Firefox file, item signature line) copied verbatim, with leading
# attributes/doc comments, in this order.
ITEMS = [
    ("gfx/wgpu_bindings/src/error.rs", "pub(crate) enum ErrorBufferType {"),
    ("gfx/wgpu_bindings/src/lib.rs", "pub struct SwapChainId(pub u64);"),
    ("gfx/wgpu_bindings/src/lib.rs", "struct ImplicitLayout<'a> {"),
    ("gfx/wgpu_bindings/src/lib.rs", "enum DeviceAction<'a> {"),
    ("gfx/wgpu_bindings/src/lib.rs", "enum QueueWriteAction {"),
    ("gfx/wgpu_bindings/src/lib.rs", "enum TextureAction<'a> {"),
    ("gfx/wgpu_bindings/src/command.rs", "pub struct BasePass<C> {"),
    ("gfx/wgpu_bindings/src/command.rs", "pub struct RecordedRenderPass {"),
    ("gfx/wgpu_bindings/src/command.rs", "pub struct RecordedComputePass {"),
    ("gfx/wgpu_bindings/src/command.rs", "pub enum RenderCommand {"),
    ("gfx/wgpu_bindings/src/command.rs", "pub enum ComputeCommand {"),
]

PREAMBLE = """// GENERATED by firefox-webgpu-decoder/build.py. Do not edit.
// Items below are copied verbatim from Firefox 128.14.0 gfx/wgpu_bindings
// (see source-lock.json for file hashes and line ranges). Only this
// preamble and the trailing include! are not from Firefox.
#![allow(dead_code, unused_imports, clippy::all)]
use arrayvec::ArrayVec;
use serde::{Deserialize, Serialize};
use std::borrow::Cow;
use wgc::command::{
    ComputePassTimestampWrites, RenderPassColorAttachment, RenderPassDepthStencilAttachment,
    RenderPassTimestampWrites,
};
use wgc::id;
use wgt::{BufferAddress, BufferSize, Color, DynamicOffset, IndexFormat};
"""


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def storage(path: Path) -> dict:
    path = path.resolve()
    mounts = []
    for line in Path("/proc/self/mountinfo").read_text().splitlines():
        fields, info = line.split(" - ", 1)
        mount = Path(fields.split()[4].replace("\\040", " "))
        if path == mount or path.is_relative_to(mount):
            mounts.append((len(str(mount)), str(mount), info.split()[0]))
    if not mounts or max(mounts)[2] in ("tmpfs", "ramfs") or str(path).startswith(("/tmp", "/dev/shm")):
        sys.exit(f"disk-backed path required: {path}")
    parent = path
    while not parent.exists():
        parent = parent.parent
    st = os.statvfs(parent)
    free = st.f_bavail * st.f_frsize
    if free < 2 << 30:
        sys.exit("less than 2 GiB free")
    return {"path": str(path), "filesystem": max(mounts)[2], "mount": max(mounts)[1], "freeBytes": free}


def extract(text: str, signature: str) -> tuple[str, int, int]:
    lines = text.splitlines()
    hits = [i for i, l in enumerate(lines) if l.strip() == signature and not l.startswith(" ")]
    if len(hits) != 1:
        sys.exit(f"signature {signature!r}: {len(hits)} matches")
    start = end = hits[0]
    while start > 0 and lines[start - 1].lstrip().startswith(("#[", "///")):
        start -= 1
    if not signature.endswith(";"):
        depth = 0
        for end in range(hits[0], len(lines)):
            code = lines[end].split("//", 1)[0]
            depth += code.count("{") - code.count("}")
            if depth == 0:
                break
        else:
            sys.exit(f"unterminated item {signature!r}")
    return "\n".join(lines[start:end + 1]) + "\n", start + 1, end + 1


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--output", type=Path, required=True)
    args = ap.parse_args()
    out = args.output.resolve()
    if not out.is_relative_to(TASK) or out == TASK:
        sys.exit(f"output must be below {TASK}")
    if out.exists():
        sys.exit(f"{out} exists; preserve old runs and pick a new name")
    st = storage(out)
    tmp = TASK / "tmp"
    for name in ("TMPDIR", "TMP", "TEMP"):
        if os.environ.get(name) != str(tmp):
            sys.exit(f"export {name}={tmp} first")
    storage(tmp)

    lock_src = FF / "Cargo.lock"
    if sha256(lock_src.read_bytes()) != FF_LOCK_SHA256:
        sys.exit("Firefox Cargo.lock hash mismatch")

    ws = out / "ws"
    (ws / "decoder/src").mkdir(parents=True)
    inputs = {}
    for rel in CRATE_FILES:
        data = (HERE / rel).read_bytes()
        inputs[rel] = sha256(data)
        dest = ws / ("decoder/" + rel if not rel.startswith("adapters/") else rel)
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(data)

    # Verbatim wire items.
    parts, extracted, ff_files = [PREAMBLE], [], {}
    for rel, sig in ITEMS:
        text = (FF / rel).read_text()
        ff_files[rel] = sha256(text.encode())
        body, a, b = extract(text, sig)
        parts.append(f"\n// ---- {rel}:{a}-{b} ----\n{body}")
        extracted.append({"file": rel, "lines": [a, b], "signature": sig, "sha256": sha256(body.encode())})
    parts.append('\ninclude!("wire_dispatch.rs");\n')
    gen = "".join(parts)
    (ws / "decoder/src/wire_generated.rs").write_text(gen)

    # Adapters: Firefox dummy-web manifests (feature lists) + adapter lib.rs.
    for crate in ("js-sys", "web-sys"):
        manifest = (FF / "build/rust/dummy-web" / crate / "Cargo.toml").read_text()
        ff_files[f"build/rust/dummy-web/{crate}/Cargo.toml"] = sha256(manifest.encode())
        if crate == "web-sys":
            manifest += '\n[dependencies]\njs-sys = { path = "../js-sys" }\n'
        (ws / "adapters" / crate / "Cargo.toml").write_text(manifest)

    shutil.copy2(lock_src, ws / "Cargo.lock")
    ff_toml = tomllib.loads((FF / "Cargo.toml").read_text())
    lines = ["[workspace]", 'members = ["decoder"]', 'resolver = "2"', "",
             "[profile.release]", "opt-level = 2", "lto = true", "codegen-units = 1",
             'panic = "abort"', 'strip = "debuginfo"', "", "[patch.crates-io]"]
    adapters = {"js-sys": "adapters/js-sys", "web-sys": "adapters/web-sys"}
    for name, spec in ff_toml["patch"]["crates-io"].items():
        spec = {"path": adapters[name]} if name in adapters else \
            {k: (str(FF / v) if k == "path" else v) for k, v in spec.items()}
        lines.append(f"{name} = {{ {', '.join(f'{k} = {json.dumps(v)}' for k, v in spec.items())} }}")
    for src, pkgs in ff_toml["patch"].items():
        if src == "crates-io":
            continue
        lines.append(f'\n[patch."{src}"]')
        for name, spec in pkgs.items():
            spec = {k: (str(FF / v) if k == "path" else v) for k, v in spec.items()}
            lines.append(f"{name} = {{ {', '.join(f'{k} = {json.dumps(v)}' for k, v in spec.items())} }}")
    (ws / "Cargo.toml").write_text("\n".join(lines) + "\n")
    cfg_in = (FF / ".cargo/config.toml.in").read_text()
    ff_files[".cargo/config.toml.in"] = sha256(cfg_in.encode())
    (ws / ".cargo").mkdir()
    (ws / ".cargo/config.toml").write_text(
        cfg_in.split("# We explicitly exclude")[0]
        + f'\n[source.vendored-sources]\ndirectory = "{FF / "third_party/rust"}"\n\n[net]\noffline = true\n')

    env = {
        "PATH": f"{TOOLCHAIN / 'bin'}:{CARGO.parent}:/usr/bin:/bin",
        "HOME": str(out),
        "TMPDIR": str(tmp), "TMP": str(tmp), "TEMP": str(tmp),
        "CARGO_HOME": str(out / "cargo-home"),
        "CARGO_TARGET_DIR": str(out / "target"),
        "CARGO_NET_OFFLINE": "true",
        "RUSTC": str(TOOLCHAIN / "bin/rustc"),
        "RUSTUP_TOOLCHAIN": "stable-x86_64-unknown-linux-gnu",
        "RUSTFLAGS": "-C link-arg=--max-memory=1073741824 -C link-arg=-zstack-size=1048576",
    }

    def run(name, cmd, cwd=ws, timeout=1800):
        (out / f"{name}.command.json").write_text(json.dumps({"cwd": str(cwd), "argv": cmd}, indent=1) + "\n")
        with open(out / f"{name}.log", "w") as log:
            r = subprocess.run(cmd, cwd=cwd, env=env, stdout=log, stderr=subprocess.STDOUT, timeout=timeout)
        if r.returncode:
            sys.exit(f"{name} failed ({r.returncode}); see {out / (name + '.log')}")
        return (out / f"{name}.log").read_text()

    run("cargo-build", [str(CARGO), "build", "--offline", "--release",
                        "--target", "wasm32-unknown-unknown", "-p", "firefox-webgpu-decoder"])
    built = out / "target/wasm32-unknown-unknown/release/firefox_webgpu_decoder.wasm"
    artifact = out / "firefox-webgpu-decoder.wasm"
    shutil.copy2(built, artifact)
    run("wasm-validate", ["wasm-validate", "--enable-all", str(artifact)])
    objdump = run("wasm-abi", ["wasm-objdump", "-x", str(artifact)])
    imports = re.findall(r"^Import\[(\d+)\]", objdump, re.M)
    if imports:
        sys.exit(f"module has imports: {imports}")
    exports = sorted(set(re.findall(r'-> "([^"]+)"', objdump.split("Export[", 1)[1].split("\n\n", 1)[0])))
    for need in ("memory", "alloc", "free", "decode", "result_ptr", "result_len", "max_input"):
        if need not in exports:
            sys.exit(f"missing export {need}")

    # Every resolved package must be a Firefox-locked package (same version,
    # source and checksum), apart from the decoder and the two path adapters.
    ff_lock = {(p["name"], p["version"]): p for p in tomllib.loads(lock_src.read_text())["package"]}
    resolved = tomllib.loads((ws / "Cargo.lock").read_text())["package"]
    local = {"firefox-webgpu-decoder", "js-sys", "web-sys"}
    mismatches = []
    for p in resolved:
        if p["name"] in local and "source" not in p:
            continue
        f = ff_lock.get((p["name"], p["version"]))
        if not f or f.get("source") != p.get("source") or f.get("checksum") != p.get("checksum"):
            mismatches.append(f"{p['name']} {p['version']}")
    if mismatches:
        sys.exit(f"packages not in Firefox lock: {mismatches}")

    data = artifact.read_bytes()
    rustc = subprocess.run([env["RUSTC"], "-V"], capture_output=True, text=True, env=env).stdout.strip()
    (out / "source-lock.json").write_text(json.dumps({
        "schema": "firefox-webgpu-w3-decoder-sources-v1",
        "firefox_tree": str(FF),
        "firefox_cargo_lock_sha256": FF_LOCK_SHA256,
        "firefox_files": ff_files,
        "extracted_items": extracted,
        "wire_generated_sha256": sha256(gen.encode()),
        "decoder_inputs": inputs,
        "resolved_lock_sha256": sha256((ws / "Cargo.lock").read_bytes()),
        "resolved_packages": len(resolved),
    }, indent=1) + "\n")
    report = {
        "pass": True,
        "artifact": str(artifact),
        "bytes": len(data),
        "sha256": sha256(data),
        "target": "wasm32-unknown-unknown",
        "rustc": rustc,
        "imports": 0,
        "exports": exports,
        "resolved_packages_all_in_firefox_lock": True,
        "storage": st,
    }
    (out / "build.json").write_text(json.dumps(report, indent=1) + "\n")
    print(json.dumps(report, indent=1))


if __name__ == "__main__":
    main()
