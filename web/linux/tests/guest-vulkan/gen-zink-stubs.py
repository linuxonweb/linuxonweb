#!/usr/bin/env python3
"""B2f: generate typed trace stubs for Vulkan core 1.0/1.1 and Zink-enabled
extension device commands that the guest ICD does not implement.

Zink resolves every core command of the reported apiVersion through
vkGetDeviceProcAddr; a NULL (or Zink's void() stub) called through a typed
function pointer traps in wasm (call_indirect signature/null), which kills the
guest process silently.  These stubs have the exact prototype, print
"GUEST_VK_TRACE UNIMPL <name>" and fail safely (VkResult -> FEATURE_NOT_PRESENT,
command-buffer commands invalidate the buffer so its submit fails).

usage: gen-zink-stubs.py vulkan_core.h > zink-stubs.inc
"""
import re, sys

SECTIONS = ["VK_VERSION_1_0", "VK_VERSION_1_1", "VK_KHR_maintenance1",
            "VK_KHR_descriptor_update_template", "VK_KHR_maintenance5",
            "VK_KHR_create_renderpass2", "VK_KHR_dynamic_rendering",
            "VK_EXT_robustness2", "VK_KHR_timeline_semaphore", "VK_EXT_debug_utils"]
# Zink calls debug-utils labels/names unguarded (the Vulkan loader always
# exports them); the ICD answers them as successful no-ops.
NOOP_PREFIX = ("vkSetDebugUtilsObject", "vkQueueBeginDebugUtilsLabel", "vkQueueEndDebugUtilsLabel",
               "vkQueueInsertDebugUtilsLabel", "vkCmdBeginDebugUtilsLabel", "vkCmdEndDebugUtilsLabel",
               "vkCmdInsertDebugUtilsLabel")

src = open(sys.argv[1]).read()
# split into "#define <SECTION> 1" blocks
parts = re.split(r"^#define (VK_[A-Za-z0-9_]+) 1$", src, flags=re.M)
blocks = {parts[i]: parts[i + 1] for i in range(1, len(parts) - 1, 2)}
proto = re.compile(r"VKAPI_ATTR\s+(.+?)\s+VKAPI_CALL\s+(vk\w+)\s*\((.*?)\);", re.S)
out = ["/* generated by gen-zink-stubs.py; do not edit */", "#ifdef GUEST_VK_ZINK"]
table = []
wrapped = []
for sec in SECTIONS:
    body = blocks.get(sec)
    if body is None:
        continue  # e.g. maintenance5 is newer than the pinned headers (zink-ext.h)
    body = body.split("#endif", 1)[0] if "VK_NO_PROTOTYPES" not in body else body
    for ret, name, params in proto.findall(body):
        params = " ".join(params.split())
        names = []
        for p in params.split(","):
            p = p.strip()
            if p == "void" or not p:
                continue
            names.append(re.findall(r"(\w+)\s*(?:\[\w*\])?$", p)[0])
        cb = names[0] if params.startswith("VkCommandBuffer ") else None
        lines = ["static VKAPI_ATTR %s VKAPI_CALL zstub_%s(%s) {" % (ret, name, params)]
        lines += ["    " + "".join("(void)%s;" % n for n in names)]
        noop = name.startswith(NOOP_PREFIX)
        if noop:
            lines += ["    return VK_SUCCESS;" if ret == "VkResult" else "    return;", "}"]
            out += lines
            table.append(name)
            wrapped.append((ret, name, params, names))
            continue
        lines += ["    ZINK_TRACE(\"UNIMPL %s\\n\");" % name]
        if cb:
            lines += ["    invalid_command(%s);" % cb]
        if ret == "VkResult":
            lines += ["    return VK_ERROR_FEATURE_NOT_PRESENT;"]
        elif ret != "void":
            lines += ["    return 0;"]
        lines += ["}"]
        out += lines
        table.append(name)
        wrapped.append((ret, name, params, names))
# call tracing wrappers (GUEST_VK_TRACE_CALLS=1): every prototype above gets a
# typed forwarder that prints "GUEST_VK_TRACE CALL <name>" before the real call.
for ret, name, params, names in wrapped:
    out.append("static PFN_%s zreal_%s;" % (name, name))
    call = "zreal_%s(%s)" % (name, ", ".join(names))
    out.append("static VKAPI_ATTR %s VKAPI_CALL ztrace_%s(%s) {" % (ret, name, params))
    out.append("    ZINK_TRACE(\"CALL %s\\n\");" % name)
    out.append("    %s%s;" % ("" if ret == "void" else "return ", call))
    out.append("}")
out.append("static PFN_vkVoidFunction zink_trace_proc(const char *name, PFN_vkVoidFunction real) {")
out.append("    if (!real) return NULL;")
for ret, name, params, names in wrapped:
    out.append("    if (!strcmp(name, \"%s\")) { zreal_%s = (PFN_%s)real; return (PFN_vkVoidFunction)ztrace_%s; }" % (name, name, name, name))
out.append("    return real;\n}")
out.append("static PFN_vkVoidFunction zink_stub_proc(const char *name) {")
for n in table:
    out.append("    if (!strcmp(name, \"%s\")) return (PFN_vkVoidFunction)zstub_%s;" % (n, n))
out.append("    return NULL;\n}\n#endif")
print("\n".join(out))
